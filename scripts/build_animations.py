#!/usr/bin/env python3
"""manim scene을 section 단위로 렌더링해서 reveal.js 덱(site/)으로 export 한다.

scene 안의 `self.next_section()` 하나가 덱의 슬라이드(클릭) 하나가 된다.

    uv run python scripts/build_animations.py                     # 전체, 1080p60
    uv run python scripts/build_animations.py -q l                # 빠른 저화질 초안
    uv run python scripts/build_animations.py animations/foo.py   # 특정 파일만

결과물:
    site/assets/anim/<Scene>/NN.mp4     section별 영상
    site/assets/anim/<Scene>/scene.json section 메타데이터
    site/assets/anim/manifest.js        덱이 읽는 전체 목록 (자동 생성)
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ANIM_DIR = ROOT / "animations"
MEDIA_DIR = ROOT / "build" / "media"
OUT_DIR = ROOT / "site" / "assets" / "anim"

# manim 의 -q 플래그 → 출력 폴더 이름 ({height}p{fps})
QUALITY_DIRS = {"l": "480p15", "m": "720p30", "h": "1080p60", "p": "1440p60", "k": "2160p60"}

# scene 파일이 아닌 모듈
SKIP = {"theme.py"}


def scene_files(paths: list[str]) -> list[Path]:
    if paths:
        return [Path(p).resolve() for p in paths]
    return sorted(p for p in ANIM_DIR.glob("*.py") if p.name not in SKIP and not p.name.startswith("_"))


def render(file: Path, quality: str) -> Path:
    sections_dir = MEDIA_DIR / "videos" / file.stem / QUALITY_DIRS[quality] / "sections"
    # 지난 렌더의 section 결과를 지워서, 삭제/이름 변경된 scene이 남지 않게 한다.
    # (partial movie 캐시는 다른 폴더라 유지되므로 재렌더는 여전히 빠르다.)
    shutil.rmtree(sections_dir, ignore_errors=True)

    cmd = [
        sys.executable, "-m", "manim", "render",
        f"-q{quality}",
        "--save_sections",
        "--media_dir", str(MEDIA_DIR),
        "-a",  # 파일 안의 모든 Scene
        str(file),
    ]  # fmt: skip
    print(f"\n▶ {file.relative_to(ROOT)}  (-q{quality})", flush=True)
    subprocess.run(cmd, check=True, cwd=ROOT)
    return sections_dir


def export(sections_dir: Path) -> list[str]:
    exported = []
    for meta_file in sorted(sections_dir.glob("*.json")):
        scene = meta_file.stem
        sections = json.loads(meta_file.read_text())

        dest = OUT_DIR / scene
        shutil.rmtree(dest, ignore_errors=True)
        dest.mkdir(parents=True)

        out_sections = []
        for i, sec in enumerate(sections):
            name = f"{i:02d}.mp4"
            shutil.copy2(sections_dir / sec["video"], dest / name)
            out_sections.append(
                {
                    "name": sec["name"],
                    "type": sec["type"],
                    "src": f"assets/anim/{scene}/{name}",
                    "duration": float(sec["duration"]),
                }
            )

        first = sections[0] if sections else {}
        meta = {
            "scene": scene,
            "width": first.get("width"),
            "height": first.get("height"),
            "sections": out_sections,
        }
        (dest / "scene.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2) + "\n")
        exported.append(f"{scene} ({len(out_sections)} sections)")
    return exported


def write_manifest() -> None:
    scenes = {}
    for meta_file in sorted(OUT_DIR.glob("*/scene.json")):
        meta = json.loads(meta_file.read_text())
        scenes[meta["scene"]] = meta
    body = json.dumps(scenes, ensure_ascii=False, indent=2)
    (OUT_DIR / "manifest.js").write_text(
        "// AUTO-GENERATED by scripts/build_animations.py — 직접 수정하지 마세요.\n"
        f"window.MANIM_SCENES = {body};\n"
    )


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("files", nargs="*", help="렌더할 scene 파일 (기본: animations/*.py 전체)")
    ap.add_argument("-q", "--quality", choices=QUALITY_DIRS, default="h", help="l=480p15 … h=1080p60 (기본) … k=4K")
    args = ap.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    exported = []
    for f in scene_files(args.files):
        exported += export(render(f, args.quality))

    if not args.files:
        # 전체 빌드일 때는 더 이상 존재하지 않는 scene 의 export 를 정리한다.
        alive = {e.split(" ")[0] for e in exported}
        for d in OUT_DIR.iterdir():
            if d.is_dir() and d.name not in alive:
                print(f"  (stale) removing {d.relative_to(ROOT)}")
                shutil.rmtree(d)
    write_manifest()

    print("\n✔ exported:")
    for e in exported:
        print(f"  - {e}")
    print(f"  → {(OUT_DIR / 'manifest.js').relative_to(ROOT)}")


if __name__ == "__main__":
    main()
